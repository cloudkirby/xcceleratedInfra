def test4()->pl.LazyFrame:
    products = pl.LazyFrame({
        "product_id": [1, 2, 3, 4, 5, 6, 7, 8, 9],
        "category": ["A", "A", "A", "B", "B", "B", "C", "C", "C"],
        "product_name": ["product1", "product2", "product3",
                         "product4", "product5", "product6",
                         "product7", "product8","product9"],
    })

    sales = pl.LazyFrame({
        "sale_id": [1, 2, 3, 4, 5, 6, 7, 8, 9],
        "product_id": [1, 2, 3, 4, 5, 6, 7, 8, 9],
        "quantity": [10, 8, 12, 5, 3, 7, 15, 10, 8],
        "revenue": [100, 120, 180, 50, 30, 70, 150, 100, 80],
    })
    """
    Your task is to write a function or SQL query that returns the top 3 selling 
    products in each product category, ranked by revenue (highest first).

    The ranking must:

    Be based on total revenue per product.
    Use dense ranking — i.e., no gaps in the ranking sequence if there's a tie.
    Output only the top 3 products per category.
    :return:
    """
    df = sales.join(products, on="product_id").select(
        pl.col("category"),
        pl.col("product_name"),
        pl.col("revenue"),
        pl.col("revenue")
        .rank("dense", descending=True)
        .over("category")
        .alias("rank"),
    ).sort("category", "rank").filter(
        pl.col("rank") <= 3)
    return print(df.collect())

def test5()->pl.LazyFrame:

    df = pl.LazyFrame({
        "user_id": [445, 742, 445, 742, 648, 742, 445, 742, 648],
        "event_id": [7765, 6558, 3634, 1374, 3124, 4521, 7563, 8541, 9512],
        "event_type": ['sign-in', 'sign-in', 'like', 'comment', 'like', 'like', 'comment', 'sign-in', 'comment'],
        "event_date": ["2022-06-30 12:00:00", "2022-06-03 12:00:00", "2022-06-05 12:00:00",
                       "2022-06-05 12:00:00", "2022-06-18 12:00:00", "2022-07-01 12:00:00",
                       "2022-07-02 12:00:00", "2022-07-05 12:00:00", "2022-07-15 12:00:00"]
    })
    df = df.select(
        pl.col("user_id"),
        pl.col("event_id"),
        pl.col("event_type"),
        pl.col("event_date").str.to_datetime("%Y-%m-%d %H:%M:%S").alias("formatted_date"),
    )
    df = df.select(
        pl.col("user_id"),
        pl.col("event_id"),
        pl.col("event_type"),
        pl.col("formatted_date").dt.year().alias("year"),
        pl.col("formatted_date").dt.month().alias("month"),
    )
    """
    Assume you're given a table containing information on user actions. 
    Write a query to obtain the number of monthly active users (MAUs) in July 2022, 
    including the month in numerical format ("1, 2, 3").

    Definition of Active User: An active user is defined as a user who has performed actions such as 'sign-in', 
    'like', or 'comment' in both the current month (July 2022) and the previous month (June 2022).
    
    :return:
    """

    df = (df.filter(
        pl.col("event_type").is_in(['sign-in', 'like', 'comment']),
        pl.col("month") == 7)
    .group_by(
        pl.col("month"),
    ).agg(
        pl.col("user_id").n_unique().alias("monthly_active_users"),
    ))

    return print(df.collect())

