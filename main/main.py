def read_bucket(bucket_name, file_name):
    client = storage.Client()

    bucket = client.get_bucket(bucket_name)
    blob = bucket.blob(file_name)
    df = pd.read_csv(blob.open('rb'))
    return df


def write_bucket(bucket_name, file_name, df):
    client = storage.Client()
    bucket = client.get_bucket(bucket_name)
    bucket.write_blob(file_name, df)

